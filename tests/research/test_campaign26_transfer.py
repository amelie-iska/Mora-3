def test_transfer_readback_in_fresh_process_replays_all_native_artifacts(tmp_path):
    import subprocess,sys,os
    from dataclasses import asdict
    from decimal import Decimal
    h,b,args=setup(tmp_path);out=tmp_path/'transfer.json'
    digest=publish_target_transfer(**args,blueprint=b,output=out)
    contract=asdict(h['selection'])
    for task in contract['tasks']:
        task['initial_reference_loss']=str(task['initial_reference_loss'])
        task['minimum_normalization_scale']=str(task['minimum_normalization_scale'])
    (tmp_path/'contract.json').write_bytes(canonical(contract))
    script=r'''
import json,sys
from pathlib import Path
from decimal import Decimal
from mora3.research.campaign26 import Campaign26,RunBudget26
from mora3.research.campaign26_transfer import TargetBlueprint,load_target_transfer,transferred_configuration
from mora3.research.mup_sweep_selection import FrozenProxySelection,FrozenValidationTask
root=Path(sys.argv[1]);d=json.loads((root/'budget/genesis.json').read_bytes())
plan=Campaign26(d['directive_sha256'],d['source_snapshot_sha256'],d['proxy_campaign_sha256'],
    tuple(d['target_seeds']),d['target_specification_sha256'])
c=json.loads((root/'contract.json').read_bytes())
c['tasks']=tuple(FrozenValidationTask(**(t|{'initial_reference_loss':Decimal(t['initial_reference_loss']),
    'minimum_normalization_scale':Decimal(t['minimum_normalization_scale'])}))for t in c['tasks'])
c['task_families']=tuple(tuple(row)for row in c['task_families'])
selection=FrozenProxySelection(**c)
wire=json.loads((root/'transfer.json').read_bytes());bp=TargetBlueprint.from_wire(wire['target_blueprint'])
result=load_target_transfer(budget=RunBudget26(root/'budget',plan),root=root,pin_directory=root/'pins',
    campaign_directory=root/'campaign',selection=selection,selection_path=root/'selection.json',
    blueprint=bp,path=root/'transfer.json',expected_sha256=sys.argv[2])
configuration,optimizer=transferred_configuration(result,plan.run_ids[24])
print(json.dumps(dict(proxy_terminal_count=result['proxy_terminal_count'],target_width=configuration.width,
    base_lr=optimizer['base_lr'],target_runs=len(result['targets']),optimizer_updates=0)))
'''
    env=os.environ.copy();env.update(PYTHONDONTWRITEBYTECODE='1',CUDA_VISIBLE_DEVICES='')
    child=subprocess.run([sys.executable,'-B','-c',script,str(tmp_path),digest],env=env,
        capture_output=True,text=True,timeout=30)
    assert child.returncode==0,child.stderr
    result=json.loads(child.stdout)
    assert result==dict(proxy_terminal_count=24,target_width=266,base_lr=.0001,target_runs=2,optimizer_updates=0)


