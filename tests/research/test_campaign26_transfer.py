def test_selected_master_lr_is_scaled_once_by_existing_muadamw_without_updates(tmp_path):
    import torch
    from test_mu_optimizer import family,target
    from mora3.model.mu_optimizer import MuAdamW
    h,b,args=setup(tmp_path);out=tmp_path/'transfer.json'
    digest=publish_target_transfer(**args,blueprint=b,output=out)
    document=load_target_transfer(**args,blueprint=b,path=out,expected_sha256=digest)
    _,request=transferred_configuration(document,h['plan'].run_ids[24])
    model,roles=target();before=[p.detach().clone()for p in model.parameters()]
    rng=torch.get_rng_state().clone();opt=MuAdamW(model,family(),roles,**request)
    groups={g['mup_aliases'][0]:g for g in opt.param_groups}
    master=float(document['selection']['frozen_transfer_hyperparameters']['learning_rate'])
    # Generic fixture's rightmost hidden width grows4->8. The target's master
    # rate itself is NOT divided, and finite/input/readout rates keep the master.
    assert groups['hidden']['lr']==master/2
    assert all(groups[key]['lr']==master for key in('input','output','vector','logZ'))
    assert not opt.state and torch.equal(rng,torch.get_rng_state())
    assert all(torch.equal(x,p)and p.grad is None for x,p in zip(before,model.parameters()))


