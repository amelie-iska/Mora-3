"""Bounded native-table ingestion and immutable candidate curation receipts.

Input tables must already carry original values and explicit evidence columns.
This adapter records the exact input bytes/rows. It does not imply that an
arbitrary reformatted table is the provider original, nor admit it for training.
"""
from dataclasses import asdict,dataclass
from collections.abc import Sequence
import csv
import io
from hashlib import sha256
import json
import math
from pathlib import Path

from .contracts import (NativeValue,SourceEvidence,StateRecord,canonical,
                        leakage_components,split_components,validate_splits,text,digest,validate_record)


@dataclass(frozen=True)
class ParsedSource(Sequence):
    """Immutable parser result bound to the exact bytes consumed, not a pathname alone."""
    source_path: str
    source_sha256: str
    parser: str
    records: tuple[StateRecord,...]
    # Assigned by the reader, never regenerated by dataclass replacement.
    parser_output_sha256: str

    def __post_init__(self):
        text(self.source_path,'source path');digest(self.source_sha256,'parsed source SHA256')
        digest(self.parser_output_sha256,'parser output SHA256')
        if self.parser not in ('native-jsonl-v1','long-cell-csv-v1'):
            raise ValueError('known source parser required')
        if type(self.records) is not tuple or not self.records:
            raise ValueError('complete nonempty parsed source records required')
        for row in self.records:validate_record(row)

    def __getitem__(self,index): return self.records[index]
    def __len__(self): return len(self.records)


def strict_json(raw):
    def unique(pairs):
        d={}
        for key,value in pairs:
            if key in d: raise ValueError('duplicate JSON key')
            d[key]=value
        return d
    def invalid(value):
        raise ValueError('nonfinite JSON numbers are not source values')
    def finite_float(value):
        parsed=float(value)
        if not math.isfinite(parsed): return invalid(value)
        return parsed
    return json.loads(raw,object_pairs_hook=unique,parse_constant=invalid,parse_float=finite_float)


def regular_file(path, *, max_bytes):
    p=Path(path).absolute()
    if (any(x.is_symlink() for x in (p,*p.parents)) or not p.is_file()
            or type(max_bytes) is not int or max_bytes<1 or p.stat().st_size>max_bytes):
        raise ValueError('bounded regular nonsymlink source file required')
    return p


def file_digest(path):
    h=sha256()
    with Path(path).open('rb') as stream:
        for chunk in iter(lambda:stream.read(1024*1024),b''):
            h.update(chunk)
    return h.hexdigest()


def _parser_output_digest(records):
    """Fingerprint the ordered canonical JSONL emitted by the source parser."""
    h=sha256()
    for row in records:
        h.update(canonical(row.wire())+b'\n')
    return h.hexdigest()


def read_native_jsonl(path, *, max_bytes=64*1024*1024,max_records=100_000):
    p=regular_file(path,max_bytes=max_bytes)
    if type(max_records) is not int or max_records<1:
        raise ValueError('positive finite record bound required')
    before=(p.stat().st_size,p.stat().st_mtime_ns);rows=[];consumed=sha256();total_bytes=0
    with p.open('rb') as stream:
        for n,line in enumerate(iter(lambda:stream.readline(max_bytes+1),b''),1):
            total_bytes+=len(line)
            if total_bytes>max_bytes:raise ValueError('source exceeds finite byte bound during readback')
            consumed.update(line)
            if n>max_records: raise ValueError('complete source exceeds record bound; no silent prefix acceptance')
            if not line.strip(): raise ValueError('blank native record line')
            rows.append(StateRecord.from_mapping(strict_json(line)))
    if not rows: raise ValueError('empty source is not training coverage')
    if (before!=(p.stat().st_size,p.stat().st_mtime_ns)
            or file_digest(p)!=consumed.hexdigest()):
        raise ValueError('source changed during readback')
    rows=tuple(rows)
    return ParsedSource(str(p.resolve()),consumed.hexdigest(),'native-jsonl-v1',rows,
                        parser_output_sha256=_parser_output_digest(rows))


def _optional(value):
    return None if value=='' else value


def _native_numeric(value):
    parsed=strict_json(value)
    if type(parsed) not in (int,float):
        raise ValueError('native numeric CSV value must be a JSON number')
    return parsed


def read_long_cell_csv(path, *, dataset_id,revision,license_id,evidence_kind,
                       max_bytes=64*1024*1024,max_rows=1_000_000):
    """Read a documented long table without creating missing observations.

    A blank value requires observed=false; zero requires observed=true. Feature
    order follows first appearance in the original table. Coordinates are
    explicit JSON arrays, and all per-record context must agree across rows.
    """
    p=regular_file(path,max_bytes=max_bytes)
    if type(max_rows) is not int or max_rows<1:
        raise ValueError('finite native-row bound required')
    with p.open('rb') as source_stream:payload=source_stream.read(max_bytes+1)
    if len(payload)>max_bytes:raise ValueError('source exceeds finite byte bound during readback')
    digest=sha256(payload).hexdigest();groups={};order=[]
    fields=('record_id','study_id','sample_id','donor_id','experiment_id','lineage_id',
            'organism','cell_type','time_value','time_unit','time_reference',
            'coordinates','coordinate_unit','coordinate_frame','intervention_ids',
            'official_split','modality','feature_id','value','unit','observed')
    with io.StringIO(payload.decode('utf-8'),newline='') as stream:
        reader=csv.DictReader(stream)
        if reader.fieldnames != list(fields):
            raise ValueError('exact documented long-cell column order required')
        previous_line=reader.line_num
        for n,row in enumerate(reader,2):
            source_lines=(str(reader.line_num) if reader.line_num==previous_line+1
                          else f'{previous_line+1}-{reader.line_num}')
            previous_line=reader.line_num
            if n-1>max_rows: raise ValueError('complete source exceeds row bound; no partial training claim')
            if None in row or any(v is None for v in row.values()):
                raise ValueError('ragged source table')
            observed={'true':True,'false':False}.get(row['observed'])
            if observed is None: raise ValueError('explicit literal true/false observed field required')
            raw=row['value']
            if not observed and raw!='': raise ValueError('missing measurement must have empty native value')
            if observed and raw=='': raise ValueError('observed measurement needs a native value')
            value=(None if not observed else raw if row['unit']=='category' else _native_numeric(raw))
            native=NativeValue(row['modality'],row['feature_id'],value,row['unit'],observed)
            meta={k:row[k] for k in fields[:-5]}
            key=row['record_id']
            if key not in groups:
                order.append(key);groups[key]=dict(meta=meta,values=[],source_rows=[])
            elif groups[key]['meta']!=meta:
                raise ValueError('per-record native context disagrees across feature rows')
            groups[key]['values'].append(native);groups[key]['source_rows'].append(source_lines)
    if file_digest(p)!=digest: raise ValueError('source bytes changed during native readback')
    records=[]
    for key in order:
        g=groups[key];m=g['meta']
        coordinates=None if not m['coordinates'] else strict_json(m['coordinates'])
        interventions=strict_json(m['intervention_ids'])
        if type(interventions) is not list or coordinates is not None and type(coordinates) is not list:
            raise ValueError('native intervention and coordinate JSON arrays required')
        source=SourceEvidence(dataset_id,revision,digest,
            f'{p.name}#csv-lines:'+','.join(str(x) for x in g['source_rows']),
            license_id,evidence_kind,m['study_id'],m['sample_id'],_optional(m['donor_id']),
            m['experiment_id'],_optional(m['lineage_id']))
        records.append(StateRecord(key,source,m['organism'],_optional(m['cell_type']),
            None if not m['time_value'] else _native_numeric(m['time_value']),
            _optional(m['time_unit']),_optional(m['time_reference']),tuple(g['values']),
            None if coordinates is None else tuple(coordinates),_optional(m['coordinate_unit']),
            _optional(m['coordinate_frame']),tuple(interventions),_optional(m['official_split'])))
    if not records: raise ValueError('empty source is not training coverage')
    records=tuple(records)
    return ParsedSource(str(p.resolve()),digest,'long-cell-csv-v1',records,
                        parser_output_sha256=_parser_output_digest(records))


def curate_records(records, *, source_path,output_directory,holdout_axes=('study','donor'),seed=20261108,links=()):
    """Write new candidates and split evidence; refuse to reuse an output folder."""
    if type(records) is not ParsedSource:
        raise ValueError('parser-bound ParsedSource required; unrelated records cannot acquire source provenance')
    records.__post_init__()
    rows=tuple(records);links=tuple(links);source=regular_file(source_path,max_bytes=1024**3)
    source_sha256=file_digest(source)
    if str(source.resolve())!=records.source_path or source_sha256!=records.source_sha256:
        raise ValueError('source differs from exact bytes consumed by parser; no curation written')
    payload=b''.join(canonical(r.wire())+b'\n' for r in rows)
    payload_sha256=sha256(payload).hexdigest()
    if payload_sha256!=records.parser_output_sha256:
        raise ValueError('records differ from canonical parser output; no curation written')
    assignments=split_components(rows,holdout_axes=holdout_axes,seed=seed,links=links)
    validate_splits(rows,assignments,holdout_axes=holdout_axes,links=links)
    groups=leakage_components(rows,holdout_axes=holdout_axes,links=links)
    out=Path(output_directory).absolute()
    if any(p.is_symlink() for p in (out,*out.parents)):
        raise ValueError('curation output must not traverse symlinks')
    out.mkdir(parents=True,exist_ok=False)
    with (out/'records.jsonl').open('xb') as stream: stream.write(payload)
    split_bytes=canonical(assignments)
    with (out/'splits.json').open('xb') as stream: stream.write(split_bytes)
    counts={s:sum(v==s for v in assignments.values()) for s in ('train','validation','test')}
    evidence_counts={k:sum(r.source.evidence_kind==k for r in rows)
                     for k in sorted({r.source.evidence_kind for r in rows})}
    if file_digest(source)!=source_sha256:
        raise ValueError('input source changed during curation; partial output retained')
    receipt=dict(schema='Mora3.SCRICurationReceipt/v1',source_path=str(source),
        source_sha256=source_sha256,parser=records.parser,
        parser_output_sha256=records.parser_output_sha256,
        input_to_parser_output_bound=True,records_sha256=payload_sha256,
        splits_sha256=sha256(split_bytes).hexdigest(),record_count=len(rows),split_counts=counts,
        leakage_components=len(groups),holdout_axes=holdout_axes,seed=seed,
        explicit_cross_source_links=links,evidence_counts=evidence_counts,
        observed_measurements=sum(x.observed for r in rows for x in r.measurements),
        missing_measurements=sum(not x.observed for r in rows for x in r.measurements),
        adapter_transforms_values=False,provider_original_values_independently_verified=False,
        imputed_values=0,source_unchanged=True,
        complete_benchmark_splits=all(counts.values()),training_admitted=False,
        required_before_training=['provider-original lineage and rights review',
            'independent native semantic verification','complete source/corpus/model owner admission'])
    with (out/'receipt.json').open('xb') as stream: stream.write(canonical(receipt))
    return receipt


def inspect_catalog(path):
    p=regular_file(path,max_bytes=4*1024*1024);d=strict_json(p.read_bytes())
    if type(d) is not dict or d.get('schema')!='Mora3.SCRISourceCatalog/v1' or type(d.get('sources')) is not list:
        raise ValueError('versioned SCRI source catalog required')
    ids=[];blockers=[];references=[];data_candidates=0
    for source in d['sources']:
        if type(source) is not dict:
            raise ValueError('catalog source must be an object')
        key=source.get('dataset_id');text(key,'dataset_id');ids.append(key)
        if source.get('data_kind') not in ('experimental','simulation','reference'):
            raise ValueError('explicit catalog data_kind required')
        if source['data_kind']=='reference' or source.get('artifact_admission_allowed') is False:
            references.append(dict(dataset_id=key,license_status=source.get('license_status'),
                artifact_use_authorized=False))
            continue
        data_candidates+=1
        if source.get('downloaded') is not True: blockers.append(f'{key}: native assets not acquired/verified by this extension')
        if source.get('license_status')!='verified': blockers.append(f'{key}: source rights unresolved or restricted')
        if not source.get('revision'): blockers.append(f'{key}: source revision not frozen')
        if source.get('training_status')!='admitted': blockers.append(f'{key}: native source/task admission pending')
    if len(set(ids))!=len(ids): raise ValueError('duplicate catalog source IDs')
    return dict(schema='Mora3.SCRICatalogInspection/v1',catalog_sha256=file_digest(p),
                candidates=len(ids),training_data_candidates=data_candidates,
                reference_only_entries=references,blockers=blockers,ready=False,
                note='Catalog labels cannot establish complete training admission.')
